#!/usr/bin/env python3
"""
對帳關閉過期的證據監測 issue（2026-11-03）。

預測清單（docs/_drugs/*.md front matter 的 predicted_indications）改過幾輪後，已經開出去的
ClinicalTrials.gov／PubMed 監測 issue 沒有機制回頭關。本腳本在 extract_drug_list.py 之後、
檢查腳本之前執行，取得全部 open 的 auto-detected 監測 issue（label clinicaltrials 或 pubmed），
符合任一條就留言並以 not_planned 關閉：

  (a) 標題沒有「→」（2026-10-16 前只按藥名開的舊版）
  (b) 藥已不在目前的 scripts/drug_list.json
  (c) issue 內文「### Predicted New Indication(s)」列的預測，一個都不在該藥目前的 predicted_indications

只有部分預測還在的：不關、不留言（避免每次排程重複留言）。
跳過：有 assignee、帶 evidence-confirmed 或 keep 類標籤、有非 bot 的人類留言、tfda／security 標籤。

用法：
  python scripts/reconcile_evidence_issues.py            # 有 GITHUB_TOKEN 才會寫入
  python scripts/reconcile_evidence_issues.py --dry-run  # 只列出會關哪些、理由（不寫任何東西）
沒有 GITHUB_TOKEN 時自動 dry-run（讀取改走公開 API）。

環境變數：RECONCILE_MAX_CLOSE（每次最多關幾筆，預設 50）、RECONCILE_SLEEP（每筆間隔秒數，預設 2.5，最少 2）、
RECONCILE_MIN_DRUGS（drug_list 少於此數就中止，避免清單產生失敗時誤關，預設 50）。
"""

import argparse
import json
import os
import re
import sys
import time
from pathlib import Path

import requests

from github_utils import GITHUB_REPO, GITHUB_TOKEN, TITLE_DRUG_RE, get_headers, list_issues

DRUG_LIST_FILE = Path(__file__).parent / "drug_list.json"
MONITOR_LABELS = ("clinicaltrials", "pubmed")
SKIP_LABELS = {"evidence-confirmed", "tfda", "security"}
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"

# 本站監測 issue 標題是英文（🔬 New Clinical Trials／📚 New Publications），留言沿用既有「🤖 Auto-closed: 」開頭
REASON_TEXT = {
    "no_arrow": "The predicted-indication list has been updated. This is a legacy monitoring issue opened by drug name only "
                "(before 2026-10-16) and does not correspond to any predicted new indication currently on the page.",
    "drug_gone": "The predicted-indication list has been updated. {drug} is no longer in the current monitoring list "
                 "(its page no longer has predicted new indications, or it is now a redirect).",
    "stale_pred": "The predicted-indication list has been updated. The prediction(s) listed in this issue "
                  "({preds}) are no longer on the page.",
}
COMMENT_TEMPLATE = "🤖 Auto-closed: {reason} Please reopen this issue if it still needs follow-up." + FOOTER


def norm(text: str) -> str:
    return re.sub(r"\s+", " ", (text or "").strip().lower())


def load_drugs() -> dict:
    with open(DRUG_LIST_FILE, encoding="utf-8") as f:
        data = json.load(f)
    return {norm(d["name"]): d for d in data.get("drugs", [])}


def issue_drug(issue: dict) -> str:
    m = TITLE_DRUG_RE.search(issue.get("title", ""))
    if m:
        return m.group(1).strip()
    m = re.search(r"^### Drug Name\s*\n+(.+)$", issue.get("body") or "", re.M)
    return m.group(1).strip() if m else ""


def issue_predictions(body: str) -> list:
    m = re.search(r"^### Predicted New Indication\(s\)\s*\n(.*?)(?=^### |\Z)", body or "", re.M | re.S)
    if not m:
        return []
    return [line[2:].strip() for line in m.group(1).splitlines() if line.startswith("- ") and line[2:].strip()]


def has_human_comment(issue: dict) -> bool:
    if not issue.get("comments"):
        return False
    url = issue["comments_url"]
    page = 1
    while True:
        r = requests.get(url, headers=get_headers(), params={"per_page": 100, "page": page}, timeout=30)
        r.raise_for_status()
        batch = r.json()
        for c in batch:
            user = c.get("user") or {}
            if user.get("type") != "Bot" and not user.get("login", "").endswith("[bot]"):
                return True
        if len(batch) < 100:
            return False
        page += 1


def skip_reason(issue: dict) -> str:
    labels = {l["name"].lower() for l in issue.get("labels", [])}
    if issue.get("assignees") or issue.get("assignee"):
        return "assigned"
    hit = sorted(l for l in labels if l in SKIP_LABELS or "keep" in l)
    if hit:
        return "label " + ",".join(hit)
    return ""


def close_reason(issue: dict, drugs: dict):
    """回傳 (理由代碼, 留言用參數)；不該關時回傳 (None, None)。"""
    title = issue.get("title", "")
    drug = issue_drug(issue)
    if "→" not in title:
        return "no_arrow", {}
    if not drug:
        return None, None
    current = drugs.get(norm(drug))
    if current is None:
        return "drug_gone", {"drug": drug}
    listed = issue_predictions(issue.get("body"))
    if not listed:
        return None, None
    now = {norm(x) for x in current.get("predicted_indications") or []}
    if any(norm(x) in now for x in listed):
        return None, None  # 全部或部分預測還在：不動
    return "stale_pred", {"preds": "; ".join(listed)}


def close_with_comment(number: int, comment: str) -> bool:
    base = f"https://api.github.com/repos/{GITHUB_REPO}/issues/{number}"
    try:
        r = requests.post(f"{base}/comments", headers=get_headers(), json={"body": comment}, timeout=30)
        r.raise_for_status()
        r = requests.patch(base, headers=get_headers(), json={"state": "closed", "state_reason": "not_planned"}, timeout=30)
        r.raise_for_status()
        return True
    except requests.RequestException as e:
        print(f"  ! #{number} 關閉失敗：{e}")
        return False


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--dry-run", action="store_true", help="只列出會關哪些與理由，不寫入 GitHub")
    args = ap.parse_args()
    dry = args.dry_run or not GITHUB_TOKEN
    max_close = int(os.environ.get("RECONCILE_MAX_CLOSE", "50"))
    pause = max(2.0, float(os.environ.get("RECONCILE_SLEEP", "2.5")))
    min_drugs = int(os.environ.get("RECONCILE_MIN_DRUGS", "50"))

    print("=" * 60)
    print(f"Reconcile evidence issues — {GITHUB_REPO}{' [DRY RUN]' if dry else ''}")
    print("=" * 60)

    drugs = load_drugs()
    if len(drugs) < min_drugs:
        print(f"drug_list 只有 {len(drugs)} 個藥（< {min_drugs}），可能產生失敗，中止對帳。")
        return 1

    issues = {}
    for label in MONITOR_LABELS:
        for issue in list_issues({"state": "open", "labels": f"auto-detected,{label}"}):
            issues[issue["number"]] = issue
    print(f"drug_list: {len(drugs)} 個藥；open 監測 issue: {len(issues)} 筆")

    planned, skipped, kept = [], {}, 0
    for number in sorted(issues, reverse=True):
        issue = issues[number]
        code, params = close_reason(issue, drugs)
        if not code:
            kept += 1
            continue
        why = skip_reason(issue)
        if not why and has_human_comment(issue):
            why = "human comment"
        if why:
            skipped[why] = skipped.get(why, 0) + 1
            print(f"  skip #{number} ({why}): {issue['title'][:90]}")
            continue
        planned.append((issue, code, params))

    by_code = {}
    for _, code, _ in planned:
        by_code[code] = by_code.get(code, 0) + 1
    print(f"\n會關閉 {len(planned)} 筆 {by_code}；保留 {kept} 筆；跳過 {sum(skipped.values())} 筆 {skipped}")
    if len(planned) > max_close:
        print(f"本次上限 {max_close} 筆，其餘留待下次排程")

    closed = 0
    for issue, code, params in planned[:max_close]:
        comment = COMMENT_TEMPLATE.format(reason=REASON_TEXT[code].format(**params))
        print(f"  {'would close' if dry else 'close'} #{issue['number']} [{code}] {issue['title'][:90]}")
        if dry:
            continue
        if close_with_comment(issue["number"], comment):
            closed += 1
        time.sleep(pause)

    if not dry:
        print(f"\n已關閉 {closed} 筆")
    return 0


if __name__ == "__main__":
    sys.exit(main())
